export const clamp = (x: number, a = 0, b = 1) => Math.min(b, Math.max(a, x));
export const lerp = (a: number, b: number, t: number) => a + (b - a) * t;
export const seg = (t: number, a: number, b: number) => clamp((t - a) / (b - a));
export const lin = (x: number) => x;
export const outCubic = (x: number) => 1 - Math.pow(1 - x, 3);
export const outQuart = (x: number) => 1 - Math.pow(1 - x, 4);
export const outExpo = (x: number) => (x >= 1 ? 1 : 1 - Math.pow(2, -10 * x));
export const inQuart = (x: number) => x * x * x * x;
export const inOutCubic = (x: number) => (x < 0.5 ? 4 * x * x * x : 1 - Math.pow(-2 * x + 2, 3) / 2);
export const inOutQuart = (x: number) => (x < 0.5 ? 8 * x * x * x * x : 1 - Math.pow(-2 * x + 2, 4) / 2);
export const EASES = { lin, cubic: outCubic, quart: outQuart, expo: outExpo, inout: inOutCubic, inoutq: inOutQuart };
export type EaseName = keyof typeof EASES;
